#!/usr/bin/env node
'use strict';

/**
 * Builds assets/icons/lucide.svg: one SVG sprite holding exactly the Lucide
 * icons the pages use (https://lucide.dev, ISC licence).
 *
 *     npm install --no-save lucide-static@0.555.0
 *     npm run build:icons
 *
 * An icon is used where the markup or a script names it:
 *
 *     <svg class="ui-icon"><use href="assets/icons/lucide.svg#wallet"></use></svg>
 *     uiIcon('wallet')                          (assets/ui.js)
 *     // ui-icons: arrow-up arrow-down          (names chosen at run time)
 *
 * Like assets/css/app.css, the output is committed: Cloudflare Pages serves
 * this repository with no build step. `npm run build:icons -- --check` fails
 * when a page names an icon the committed sprite does not have.
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'assets', 'icons', 'lucide.svg');
const CHECK = process.argv.includes('--check');

function walk(dir, files = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (['node_modules', '.git', 'tests', 'scripts', 'apps-script', 'docs', 'supabase'].includes(entry.name)) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, files);
    else if (/\.(html|js)$/.test(entry.name)) files.push(full);
  }
  return files;
}

/** Every icon name the frontend refers to. */
function usedIcons() {
  const names = new Set();
  for (const file of walk(ROOT)) {
    const text = fs.readFileSync(file, 'utf8');
    for (const m of text.matchAll(/lucide\.svg#([a-z0-9-]+)/g)) names.add(m[1]);
    for (const m of text.matchAll(/uiIcon\(\s*['"]([a-z0-9-]+)['"]/g)) names.add(m[1]);
    for (const m of text.matchAll(/data-icon="([a-z0-9-]+)"/g)) names.add(m[1]);
    for (const m of text.matchAll(/ui-icons:([a-z0-9 -]+)/g)) m[1].trim().split(/\s+/).forEach(name => names.add(name));
  }
  return [...names].sort();
}

function symbolFor(name) {
  const file = path.join(ROOT, 'node_modules', 'lucide-static', 'icons', `${name}.svg`);
  if (!fs.existsSync(file)) throw new Error(`Lucide has no icon "${name}" (looked in ${file}).`);
  const svg = fs.readFileSync(file, 'utf8');
  const inner = svg.replace(/<!--[\s\S]*?-->/g, '').replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '')
    .replace(/\s*\n\s*/g, '');
  return `<symbol id="${name}" viewBox="0 0 24 24">${inner}</symbol>`;
}

const names = usedIcons();

if (CHECK) {
  const sprite = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  const missing = names.filter(name => !sprite.includes(`id="${name}"`));
  if (missing.length) {
    console.error(`assets/icons/lucide.svg lacks: ${missing.join(', ')} -- run npm run build:icons`);
    process.exit(1);
  }
  console.log(`assets/icons/lucide.svg has all ${names.length} icons the pages use.`);
  process.exit(0);
}

const body = names.map(symbolFor).join('\n');
// The ISC and MIT notices ask to travel with every copy, and the sprite is the
// copy that is served, so the licence goes inside it rather than beside it.
const licence = fs.readFileSync(path.join(ROOT, 'node_modules', 'lucide-static', 'LICENSE'), 'utf8')
  .replace(/--/g, '\u2010\u2010').trim();
// Stroke attributes on the root are inherited by every <use>, so each icon is
// drawn exactly as Lucide draws it, in the colour of the text around it.
const sprite = `<!-- Generated by scripts/build-icons.js from lucide-static (https://lucide.dev). Do not edit.

${licence}
-->
<svg xmlns="http://www.w3.org/2000/svg" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">
${body}
</svg>
`;
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, sprite);
console.log(`assets/icons/lucide.svg: ${names.length} icons, ${sprite.length} bytes.`);
